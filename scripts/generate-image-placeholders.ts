/**
 * @fileoverview Generates the inlined blur previews used by every next/image.
 *
 * @project Skyline Luxury Residences
 * @type {FrontendEngineeringTask}
 * @framework Next.js (App Router) + TypeScript
 *
 * @description
 * The image optimizer needs ~0.25-0.37 s per size on a cold cache, so a first visit would otherwise
 * show empty boxes while every card decodes. This writes one tiny preview per file in
 * public/images into src/lib/media/image-placeholders.ts, which the server renders inline as
 * `blurDataURL` — a colour-accurate first paint with no extra request.
 *
 * Dimensions and quality match next-image-loader (largest side 8 px, quality 70) so a generated
 * preview is indistinguishable from one Next would derive from a static import.
 *
 * Usage: `npm run images:placeholders` after adding or replacing anything in public/images.
 *
 * @module scripts/generate-image-placeholders
 */
import { mkdirSync } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, extname, join, relative, resolve } from "node:path";
import process from "node:process";
import sharp from "sharp";

const SOURCE_DIR = resolve(process.cwd(), "public/images");
const PUBLIC_DIR = resolve(process.cwd(), "public");
const OUTPUT_FILE = resolve(process.cwd(), "src/lib/media/image-placeholders.ts");
const BLUR_SIZE = 8;
const BLUR_QUALITY = 70;
const FORMATS = new Map<string, "jpeg" | "png" | "webp" | "avif">([
  [".jpg", "jpeg"],
  [".jpeg", "jpeg"],
  [".png", "png"],
  [".webp", "webp"],
  [".avif", "avif"],
]);

async function listImages(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => listImages(join(dir, entry.name))));
  return entries
    .filter((entry) => entry.isFile() && FORMATS.has(extname(entry.name).toLowerCase()))
    .map((entry) => join(dir, entry.name))
    .flat()
    .concat(nested.flat())
    .sort();
}

/** Scales the longest side to 8 px, matching how Next blurs a static import. */
function previewSize(width: number, height: number): { width: number; height: number } {
  return width >= height
    ? { width: BLUR_SIZE, height: Math.max(Math.round((height / width) * BLUR_SIZE), 1) }
    : { width: Math.max(Math.round((width / height) * BLUR_SIZE), 1), height: BLUR_SIZE };
}

async function build(): Promise<void> {
  const files = await listImages(SOURCE_DIR);
  const entries = await Promise.all(files.map(async (file) => {
    const buffer = await readFile(file);
    const metadata = await sharp(buffer).metadata();
    const src = `/${relative(PUBLIC_DIR, file).split("\\").join("/")}`;
    const format = FORMATS.get(extname(file).toLowerCase());

    if (!metadata.width || !metadata.height || !format) {
      console.warn(`Skipping ${file}: unknown dimensions or unsupported format.`);
      return null;
    }
    if ((metadata.pages ?? 1) > 1) {
      console.warn(`Skipping ${file}: animated images have no still preview.`);
      return null;
    }

    const size = previewSize(metadata.width, metadata.height);
    const preview = await sharp(buffer)
      .resize(size.width, size.height, { fit: "inside", withoutEnlargement: true })
      .toFormat(format, { quality: BLUR_QUALITY })
      .toBuffer();

    return {
      src,
      declaration: `  ${JSON.stringify(src)}: ${JSON.stringify(`data:image/${format};base64,${preview.toString("base64")}`)},`,
      bytes: preview.length,
    };
  }));

  const resolved = entries.filter((entry): entry is NonNullable<typeof entry> => entry !== null);
  const total = resolved.reduce((sum, entry) => sum + entry.bytes, 0);
  const body = [
    "/**",
    " * @fileoverview Inlined blur previews for every image served from public/images.",
    " *",
    " * @description",
    " * GENERATED by scripts/generate-image-placeholders.ts — do not edit by hand.",
    " * Regenerate with `npm run images:placeholders` after adding or replacing an image;",
    " * tests/unit/image-placeholders.test.ts fails when this map and public/images drift.",
    " *",
    " * @module media/image-placeholders",
    " */",
    "/** Keyed by the path used as a next/image `src`. */",
    "export const IMAGE_PLACEHOLDERS: Readonly<Record<string, string>> = Object.freeze({",
    resolved.map((entry) => entry.declaration).join("\n"),
    "});",
    "",
  ].join("\n");

  mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
  await writeFile(OUTPUT_FILE, body, "utf8");
  console.log(`Wrote ${resolved.length} previews (${total} bytes of image data) to ${relative(process.cwd(), OUTPUT_FILE)}.`);
}

build().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
